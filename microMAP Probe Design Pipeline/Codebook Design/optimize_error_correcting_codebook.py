Code = tuple[int, ...]


# ============================================================
# Utilities
# ============================================================

def hamming_distance(code1: Sequence[int], code2: Sequence[int]) -> int:
    """Return the Hamming distance between two equal-length codes."""
    if len(code1) != len(code2):
        raise ValueError("Hamming distance requires codes of equal length.")
    return sum(a != b for a, b in zip(code1, code2))


def unique_preserve_order(codes: Sequence[Code]) -> list[Code]:
    """Remove duplicate codes while preserving order."""
    seen = set()
    result = []
    for code in codes:
        if code not in seen:
            seen.add(code)
            result.append(code)
    return result


def min_pairwise_distance(codebook: Sequence[Code]) -> Optional[int]:
    """Return the minimum pairwise Hamming distance."""
    if len(codebook) < 2:
        return None

    minimum = math.inf
    for i in range(len(codebook)):
        for j in range(i + 1, len(codebook)):
            distance = hamming_distance(codebook[i], codebook[j])
            if distance < minimum:
                minimum = distance

    return int(minimum)


