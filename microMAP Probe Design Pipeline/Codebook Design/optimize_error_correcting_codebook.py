#!/usr/bin/env python3
"""
==============================================================================
Error-Correcting Codebook Optimization Pipeline
==============================================================================

Purpose:
    Selects a large error-correcting subset from an initial 4-of-N codebook
    under a user-defined minimum Hamming-distance constraint.

Core Method:
    1. Reads an initial candidate codebook generated by
       `generate_initial_codebook.py`.
    2. Uses simulated annealing to select an initial seed code with a relatively
       large minimum Hamming distance to the remaining candidate codes.
    3. Progressively relaxes the Hamming-distance requirement from D_start to
       D_min and greedily extends the selected codebook at each distance level.
    4. Repeats the search using independent initializations and retains the
       largest valid codebook identified.
    5. Validates the final codebook by calculating its observed minimum pairwise
       Hamming distance.

Input Modes:
    1. F/N Lookup:
       Specify F and N. The script automatically reads:

           initial_codebook/codebook_F{F}N{N}.csv

    2. Direct CSV:
       Alternatively, provide the path to an initial codebook using `--input`.

Execution:
    - CPU single-process and multiprocessing modes are supported.
    - CUDA GPU acceleration is optionally available through PyTorch.
    - If `--d-start` is not specified, the search starts from N.
    - The search can terminate according to target codebook size, elapsed time,
      and/or maximum iteration count.

Example Usage:
    # Automatically locate the initial codebook using F and N
    python optimize_error_correcting_codebook.py --F 1 --N 8 --d-min 4 \
        --threshold 14 --time-limit 7200 --max-iterations 100 \
        --workers 8 --device auto

    # Directly specify an initial codebook
    python optimize_error_correcting_codebook.py \
        --input initial_codebook/codebook_F1N8.csv --d-min 4 \
        --threshold 14 --time-limit 7200 --max-iterations 100 \
        --workers 8 --device auto

Outputs:
    1. Optimized error-correcting codebook in CSV format.
    2. JSON metadata containing search parameters, execution information,
       progressive search trace, and final Hamming-distance validation.

==============================================================================
"""

