def read_codebook_csv(filename: Path) -> list[Code]:
    """Read an initial codebook CSV."""
    if not filename.exists():
        raise FileNotFoundError(f"Input file does not exist: {filename}")

    with filename.open("r", newline="", encoding="utf-8-sig") as handle:
        rows = list(csv.reader(handle))

    if len(rows) < 2:
        raise ValueError(f"No code rows found in {filename}")

    codebook = []

    for row_number, row in enumerate(rows[1:], start=2):
        if len(row) < 2:
            continue

        values = row[1:]

        if any(value.strip() == "" for value in values):
            raise ValueError(
                f"Missing code value at row {row_number} in {filename}"
            )

        try:
            code = tuple(int(value.strip()) for value in values)
        except ValueError as exc:
            raise ValueError(
                f"Non-integer code value at row {row_number} in {filename}"
            ) from exc

        if any(value < 0 for value in code):
            raise ValueError(
                f"Negative code value at row {row_number} in {filename}"
            )

        codebook.append(code)

    if not codebook:
        raise ValueError(f"No codes found in {filename}")

    lengths = {len(code) for code in codebook}
    if len(lengths) != 1:
        raise ValueError(
            f"Code lengths are inconsistent in {filename}: {sorted(lengths)}"
        )

    return codebook


def write_codebook_csv(codebook: Sequence[Code], output_file: Path) -> None:
    """Write the optimized codebook to CSV."""
    if not codebook:
        raise ValueError("Cannot write an empty codebook.")

    output_file.parent.mkdir(parents=True, exist_ok=True)

    n_rounds = len(codebook[0])
    header = [""] + [f"Round{i}" for i in range(1, n_rounds + 1)]

    with output_file.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(header)

        for index, code in enumerate(codebook, start=1):
            writer.writerow([f"code{index}", *code])


def resolve_input_file(args) -> Path:
    """
    Resolve input from either:
    1) --input <csv>
    2) --F <F> --N <N>
    """
    if args.input is not None:
        if args.F is not None or args.N is not None:
            raise ValueError(
                "Use either --input OR --F/--N, not both."
            )
        return args.input

    if args.F is None and args.N is None:
        raise ValueError(
            "No initial codebook was specified.\n"
            "Provide either:\n"
            "  1) --input <codebook.csv>\n"
            "  2) --F <F> --N <N>"
        )

    if args.F is None or args.N is None:
        raise ValueError("--F and --N must be provided together.")

    input_file = (
        args.initial_codebook_dir
        / f"codebook_F{args.F}N{args.N}.csv"
    )

    if not input_file.exists():
        raise FileNotFoundError(
            f"Initial codebook was not found:\n"
            f"  {input_file}\n\n"
            f"Generate it first with:\n"
            f"  python generate_initial_codebook.py "
            f"--F {args.F} --N {args.N}"
        )

    return input_file


def infer_codebook_parameters(codebook: Sequence[Code]) -> tuple[int, int]:
    """Infer F and N from the codebook contents."""
    n_rounds = len(codebook[0])
    f_value = max(max(code) for code in codebook)

    if f_value < 1:
        raise ValueError(
            "The input codebook does not contain any non-zero symbol."
        )

    return f_value, n_rounds


# ============================================================
# Stopping conditions
# ============================================================

def should_stop_search(
    *,
    start_time: float,
    iteration_count: int,
    best_size: int,
    threshold: int,
    time_limit: float,
    max_iterations: int,
    stop_by_threshold: bool,
    stop_by_time: bool,
    stop_by_iteration: bool,
) -> tuple[bool, list[str]]:
    reasons = []

    if stop_by_threshold and best_size >= threshold:
        reasons.append(f"threshold reached: {best_size} >= {threshold}")

    if stop_by_time and time.time() - start_time >= time_limit:
        reasons.append(f"time limit reached: {time_limit} seconds")

    if stop_by_iteration and iteration_count >= max_iterations:
        reasons.append(
            f"iteration limit reached: {iteration_count} >= {max_iterations}"
        )

    return bool(reasons), reasons


# ============================================================
# CPU search
# ============================================================

def simulated_annealing_cpu(
    allowed_codes: Sequence[Code],
    initial_temperature: float,
    cooling_rate: float,
) -> int:
    num_codes = len(allowed_codes)
    code_length = len(allowed_codes[0])

    if num_codes == 1:
        return 0

    def objective(index: int) -> int:
        code = allowed_codes[index]
        best_min_distance = code_length + 1

        for other_index, other_code in enumerate(allowed_codes):
            if other_index == index:
                continue

            distance = hamming_distance(code, other_code)
            if distance < best_min_distance:
                best_min_distance = distance

        return best_min_distance

    current_index = random.randrange(num_codes)
    current_value = objective(current_index)

    best_index = current_index
    best_value = current_value

    temperature = initial_temperature

    while temperature > 1:
        new_index = random.randrange(num_codes)
        new_value = objective(new_index)

        if (
            new_value > current_value
            or random.random()
            < math.exp((new_value - current_value) / temperature)
        ):
            current_index = new_index
            current_value = new_value

            if new_value > best_value:
                best_index = new_index
                best_value = new_value

        temperature *= cooling_rate

    return best_index


def greedy_extend_codebook_cpu(
    allowed_codes: Sequence[Code],
    seed_codebook: Sequence[Code],
    min_distance: int,
) -> list[Code]:
    selected = list(seed_codebook)
    selected_set = set(selected)

    candidates = [
        code for code in allowed_codes
        if code not in selected_set
    ]

    random.shuffle(candidates)

    if selected:
        candidates.sort(
            key=lambda code: min(
                hamming_distance(code, selected_code)
                for selected_code in selected
            ),
            reverse=True,
        )

    for code in candidates:
        if all(
            hamming_distance(code, selected_code) >= min_distance
            for selected_code in selected
        ):
            selected.append(code)
            selected_set.add(code)

    return selected


def progressive_one_run_cpu(
    allowed_codes: Sequence[Code],
    d_start: int,
    d_min: int,
    initial_temperature: float,
    cooling_rate: float,
) -> tuple[list[Code], list[tuple[int, int, int]], Code]:
    initial_index = simulated_annealing_cpu(
        allowed_codes=allowed_codes,
        initial_temperature=initial_temperature,
        cooling_rate=cooling_rate,
    )

    initial_code = allowed_codes[initial_index]
    selected = [initial_code]
    trace = []

    for distance in range(d_start, d_min - 1, -1):
        before = len(selected)

        selected = greedy_extend_codebook_cpu(
            allowed_codes=allowed_codes,
            seed_codebook=selected,
            min_distance=distance,
        )

        trace.append((distance, before, len(selected)))

    return selected, trace, initial_code


def cpu_worker(args):
    (
        run_id,
        allowed_codes,
        d_start,
        d_min,
        initial_temperature,
        cooling_rate,
        base_seed,
    ) = args

    if base_seed is None:
        seed = (time.time_ns() + os.getpid() + run_id) % (2**32)
    else:
        seed = base_seed + run_id

    random.seed(seed)

    return progressive_one_run_cpu(
        allowed_codes=allowed_codes,
        d_start=d_start,
        d_min=d_min,
        initial_temperature=initial_temperature,
        cooling_rate=cooling_rate,
    )


def optimize_codebook_cpu(
    *,
    allowed_codes: Sequence[Code],
    d_start: int,
    d_min: int,
    threshold: int,
    time_limit: float,
    max_iterations: int,
    workers: int,
    random_seed: Optional[int],
    stop_by_threshold: bool,
    stop_by_time: bool,
    stop_by_iteration: bool,
    initial_temperature: float = 100.0,
    cooling_rate: float = 0.99,
) -> tuple[list[Code], int, list[tuple[int, int, int]]]:
    start_time = time.time()
    iteration_count = 0

    best_codebook = []
    best_trace = []

    def report_new_best(codebook, trace, initial_code, iteration):
        print(
            f"\n[CPU] New best size = {len(codebook)} "
            f"at iteration {iteration}"
        )
        print(
            "[CPU] Initial code = "
            + "".join(str(value) for value in initial_code)
        )
        for distance, before, after in trace:
            print(f"[CPU] D={distance}: {before} -> {after}")

    if workers == 1:
        while True:
            stop, reasons = should_stop_search(
                start_time=start_time,
                iteration_count=iteration_count,
                best_size=len(best_codebook),
                threshold=threshold,
                time_limit=time_limit,
                max_iterations=max_iterations,
                stop_by_threshold=stop_by_threshold,
                stop_by_time=stop_by_time,
                stop_by_iteration=stop_by_iteration,
            )

            if stop:
                for reason in reasons:
                    print(f"[CPU] Stop: {reason}")
                break

            iteration_count += 1

            if random_seed is not None:
                random.seed(random_seed + iteration_count)

            codebook, trace, initial_code = progressive_one_run_cpu(
                allowed_codes=allowed_codes,
                d_start=d_start,
                d_min=d_min,
                initial_temperature=initial_temperature,
                cooling_rate=cooling_rate,
            )

            if len(codebook) > len(best_codebook):
                best_codebook = codebook
                best_trace = trace
                report_new_best(
                    codebook,
                    trace,
                    initial_code,
                    iteration_count,
                )

        return best_codebook, iteration_count, best_trace

    with Pool(processes=workers) as pool:
        while True:
            stop, reasons = should_stop_search(
                start_time=start_time,
                iteration_count=iteration_count,
                best_size=len(best_codebook),
                threshold=threshold,
                time_limit=time_limit,
                max_iterations=max_iterations,
                stop_by_threshold=stop_by_threshold,
                stop_by_time=stop_by_time,
                stop_by_iteration=stop_by_iteration,
            )

            if stop:
                for reason in reasons:
                    print(f"[CPU] Stop: {reason}")
                break

            if stop_by_iteration:
                remaining = max_iterations - iteration_count
                batch_size = min(workers, remaining)
            else:
                batch_size = workers

            if batch_size <= 0:
                break

            tasks = []

            for offset in range(batch_size):
                run_id = iteration_count + offset + 1

                tasks.append(
                    (
                        run_id,
                        allowed_codes,
                        d_start,
                        d_min,
                        initial_temperature,
                        cooling_rate,
                        random_seed,
                    )
                )

            results = pool.map(cpu_worker, tasks)

            for codebook, trace, initial_code in results:
                iteration_count += 1

                if len(codebook) > len(best_codebook):
                    best_codebook = codebook
                    best_trace = trace
                    report_new_best(
                        codebook,
                        trace,
                        initial_code,
                        iteration_count,
                    )

                if (
                    stop_by_threshold
                    and len(best_codebook) >= threshold
                ):
                    print(
                        "[CPU] Stop: threshold reached "
                        f"({len(best_codebook)} >= {threshold})"
                    )
                    return (
                        best_codebook,
                        iteration_count,
                        best_trace,
                    )

    return best_codebook, iteration_count, best_trace


# ============================================================
# GPU search
# ============================================================

def simulated_annealing_gpu(
    codes_tensor,
    initial_temperature: float,
    cooling_rate: float,
) -> int:
    num_codes, code_length = codes_tensor.shape

    if num_codes == 1:
        return 0

    def objective(index: int) -> int:
        code_vector = codes_tensor[index]
        distances = (codes_tensor != code_vector).sum(dim=1)
        distances[index] = code_length + 1
        return int(distances.min().item())

    current_index = random.randrange(num_codes)
    current_value = objective(current_index)

    best_index = current_index
    best_value = current_value

    temperature = initial_temperature

    while temperature > 1:
        new_index = random.randrange(num_codes)
        new_value = objective(new_index)

        if (
            new_value > current_value
            or random.random()
            < math.exp((new_value - current_value) / temperature)
        ):
            current_index = new_index
            current_value = new_value

            if new_value > best_value:
                best_index = new_index
                best_value = new_value

        temperature *= cooling_rate

    return best_index


def greedy_extend_codebook_gpu(
    codes_tensor,
    seed_indices: Sequence[int],
    min_distance: int,
) -> list[int]:
    device = codes_tensor.device
    num_codes, code_length = codes_tensor.shape

    selected_indices = list(seed_indices)

    selected_mask = torch.zeros(
        num_codes,
        dtype=torch.bool,
        device=device,
    )
    selected_mask[selected_indices] = True

    min_distances = torch.full(
        (num_codes,),
        fill_value=code_length + 1,
        dtype=torch.int16,
        device=device,
    )

    for selected_index in selected_indices:
        distances = (
            codes_tensor != codes_tensor[selected_index]
        ).sum(dim=1).to(torch.int16)

        min_distances = torch.minimum(
            min_distances,
            distances,
        )

    min_distances[selected_mask] = -1

    candidate_order = torch.argsort(
        min_distances,
        descending=True,
    ).tolist()

    for index in candidate_order:
        if selected_mask[index]:
            continue

        candidate = codes_tensor[index:index + 1]
        selected_vectors = codes_tensor[selected_indices]

        distances = (
            selected_vectors != candidate
        ).sum(dim=1)

        if int(distances.min().item()) >= min_distance:
            selected_indices.append(index)
            selected_mask[index] = True

    return selected_indices


def progressive_one_run_gpu(
    codes_tensor,
    d_start: int,
    d_min: int,
    initial_temperature: float,
    cooling_rate: float,
) -> tuple[list[int], list[tuple[int, int, int]], int]:
    initial_index = simulated_annealing_gpu(
        codes_tensor=codes_tensor,
        initial_temperature=initial_temperature,
        cooling_rate=cooling_rate,
    )

    selected_indices = [initial_index]
    trace = []

    for distance in range(d_start, d_min - 1, -1):
        before = len(selected_indices)

        selected_indices = greedy_extend_codebook_gpu(
            codes_tensor=codes_tensor,
            seed_indices=selected_indices,
            min_distance=distance,
        )

        trace.append(
            (distance, before, len(selected_indices))
        )

    return selected_indices, trace, initial_index


def optimize_codebook_gpu(
    *,
    allowed_codes: Sequence[Code],
    d_start: int,
    d_min: int,
    threshold: int,
    time_limit: float,
    max_iterations: int,
    random_seed: Optional[int],
    stop_by_threshold: bool,
    stop_by_time: bool,
    stop_by_iteration: bool,
    initial_temperature: float = 100.0,
    cooling_rate: float = 0.99,
) -> tuple[list[Code], int, list[tuple[int, int, int]]]:
    if not TORCH_AVAILABLE:
        raise RuntimeError("PyTorch is not installed.")

    if not torch.cuda.is_available():
        raise RuntimeError("CUDA is not available.")

    device = torch.device("cuda")

    codes_tensor = torch.tensor(
        allowed_codes,
        dtype=torch.int16,
        device=device,
    )

    start_time = time.time()
    iteration_count = 0

    best_indices = []
    best_trace = []

    while True:
        stop, reasons = should_stop_search(
            start_time=start_time,
            iteration_count=iteration_count,
            best_size=len(best_indices),
            threshold=threshold,
            time_limit=time_limit,
            max_iterations=max_iterations,
            stop_by_threshold=stop_by_threshold,
            stop_by_time=stop_by_time,
            stop_by_iteration=stop_by_iteration,
        )

        if stop:
            for reason in reasons:
                print(f"[GPU] Stop: {reason}")
            break

        iteration_count += 1

        if random_seed is not None:
            current_seed = random_seed + iteration_count
            random.seed(current_seed)
            torch.manual_seed(current_seed)
            torch.cuda.manual_seed_all(current_seed)

        indices, trace, initial_index = progressive_one_run_gpu(
            codes_tensor=codes_tensor,
            d_start=d_start,
            d_min=d_min,
            initial_temperature=initial_temperature,
            cooling_rate=cooling_rate,
        )

        if len(indices) > len(best_indices):
            best_indices = indices
            best_trace = trace

            print(
                f"\n[GPU] New best size = {len(best_indices)} "
                f"at iteration {iteration_count}"
            )

            print(
                "[GPU] Initial code = "
                + "".join(
                    str(value)
                    for value in allowed_codes[initial_index]
                )
            )

            for distance, before, after in trace:
                print(f"[GPU] D={distance}: {before} -> {after}")

    best_codebook = [
        allowed_codes[index]
        for index in best_indices
    ]

    return best_codebook, iteration_count, best_trace


