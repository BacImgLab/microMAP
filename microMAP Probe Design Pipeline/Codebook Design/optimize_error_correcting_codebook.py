def select_device(requested_device: str) -> str:
    cuda_available = (
        TORCH_AVAILABLE
        and torch is not None
        and torch.cuda.is_available()
    )

    if requested_device == "gpu":
        if not TORCH_AVAILABLE:
            raise RuntimeError(
                "--device gpu was requested, but PyTorch is not installed."
            )

        if not cuda_available:
            raise RuntimeError(
                "--device gpu was requested, but CUDA is not available."
            )

        return "gpu"

    if requested_device == "auto" and cuda_available:
        return "gpu"

    return "cpu"


def validate_parameters(
    *,
    code_length: int,
    d_start: int,
    d_min: int,
    threshold: int,
    time_limit: float,
    max_iterations: int,
    workers: int,
    stop_by_threshold: bool,
    stop_by_time: bool,
    stop_by_iteration: bool,
) -> None:
    if d_start > code_length:
        raise ValueError(
            f"d_start ({d_start}) cannot exceed "
            f"code length N ({code_length})."
        )

    if d_start < 0:
        raise ValueError("d_start must be non-negative.")

    if d_min > d_start:
        raise ValueError(
            f"d_min ({d_min}) cannot exceed d_start ({d_start})."
        )

    if d_min < 0:
        raise ValueError("d_min must be non-negative.")

    if threshold < 1:
        raise ValueError("threshold must be >= 1.")

    if time_limit <= 0:
        raise ValueError("time_limit must be > 0.")

    if max_iterations < 1:
        raise ValueError("max_iterations must be >= 1.")

    if workers < 1:
        raise ValueError("workers must be >= 1.")

    if not (
        stop_by_threshold
        or stop_by_time
        or stop_by_iteration
    ):
        raise ValueError(
            "At least one stopping condition must be enabled."
        )


def build_output_stem(
    *,
    f_value: int,
    n_rounds: int,
    d_start: int,
    d_min: int,
    code_count: int,
) -> str:
    return (
        "error_correcting_codebook"
        f"_F{f_value}"
        f"N{n_rounds}"
        f"_Dstart{d_start}"
        f"_Dmin{d_min}"
        f"_count{code_count}"
    )


# ============================================================
# Main
# ============================================================

def main() -> None:
    args = build_parser().parse_args()

    input_file = resolve_input_file(args)

    raw_codebook = read_codebook_csv(input_file)
    codebook = unique_preserve_order(raw_codebook)

    inferred_F, inferred_N = infer_codebook_parameters(codebook)

    if args.input is None:
        if inferred_N != args.N:
            raise ValueError(
                f"Input code length ({inferred_N}) "
                f"does not match --N {args.N}."
            )

        if inferred_F != args.F:
            raise ValueError(
                f"Maximum symbol in input codebook ({inferred_F}) "
                f"does not match --F {args.F}."
            )

        f_value = args.F
        n_rounds = args.N

    else:
        f_value = inferred_F
        n_rounds = inferred_N

    d_start = (
        args.d_start
        if args.d_start is not None
        else n_rounds
    )

    validate_parameters(
        code_length=n_rounds,
        d_start=d_start,
        d_min=args.d_min,
        threshold=args.threshold,
        time_limit=args.time_limit,
        max_iterations=args.max_iterations,
        workers=args.workers,
        stop_by_threshold=args.stop_by_threshold,
        stop_by_time=args.stop_by_time,
        stop_by_iteration=args.stop_by_iteration,
    )

    device = select_device(args.device)

    if args.seed is not None:
        random.seed(args.seed)

    print(
        "========== Error-correcting codebook optimization =========="
    )
    print(f"Input = {input_file}")
    print(f"F = {f_value}")
    print(f"N = {n_rounds}")
    print(f"Initial codes = {len(raw_codebook)}")

    if len(codebook) != len(raw_codebook):
        print(f"Unique codes = {len(codebook)}")
        print(
            f"Removed duplicates = "
            f"{len(raw_codebook) - len(codebook)}"
        )

    print(f"D_start = {d_start}")
    print(f"D_min = {args.d_min}")
    print(f"Target size = {args.threshold}")
    print(f"Device = {device}")

    if device == "cpu":
        print(f"CPU workers = {args.workers}")

    search_start = time.time()

    if device == "gpu":
        selected_codebook, iterations, trace = optimize_codebook_gpu(
            allowed_codes=codebook,
            d_start=d_start,
            d_min=args.d_min,
            threshold=args.threshold,
            time_limit=args.time_limit,
            max_iterations=args.max_iterations,
            random_seed=args.seed,
            stop_by_threshold=args.stop_by_threshold,
            stop_by_time=args.stop_by_time,
            stop_by_iteration=args.stop_by_iteration,
        )
    else:
        selected_codebook, iterations, trace = optimize_codebook_cpu(
            allowed_codes=codebook,
            d_start=d_start,
            d_min=args.d_min,
            threshold=args.threshold,
            time_limit=args.time_limit,
            max_iterations=args.max_iterations,
            workers=args.workers,
            random_seed=args.seed,
            stop_by_threshold=args.stop_by_threshold,
            stop_by_time=args.stop_by_time,
            stop_by_iteration=args.stop_by_iteration,
        )

    elapsed_seconds = time.time() - search_start

    if not selected_codebook:
        raise RuntimeError(
            "Search finished without producing a codebook."
        )

    observed_min_distance = min_pairwise_distance(
        selected_codebook
    )

    if (
        observed_min_distance is not None
        and observed_min_distance < args.d_min
    ):
        raise RuntimeError(
            "Final codebook failed distance validation: "
            f"observed {observed_min_distance} "
            f"< required {args.d_min}."
        )

    output_stem = build_output_stem(
        f_value=f_value,
        n_rounds=n_rounds,
        d_start=d_start,
        d_min=args.d_min,
        code_count=len(selected_codebook),
    )

    output_csv = (
        args.output_dir
        / f"{output_stem}.csv"
    )

    metadata_json = (
        args.output_dir
        / f"{output_stem}.json"
    )

    write_codebook_csv(
        codebook=selected_codebook,
        output_file=output_csv,
    )

    metadata = {
        "input_file": str(input_file),
        "F": f_value,
        "N": n_rounds,
        "initial_code_count": len(raw_codebook),
        "unique_initial_code_count": len(codebook),
        "selected_code_count": len(selected_codebook),
        "D_start": d_start,
        "D_min": args.d_min,
        "observed_min_pairwise_distance": observed_min_distance,
        "threshold": args.threshold,
        "time_limit_seconds": args.time_limit,
        "max_iterations": args.max_iterations,
        "iterations_completed": iterations,
        "elapsed_seconds": elapsed_seconds,
        "device": device,
        "workers": (
            args.workers
            if device == "cpu"
            else None
        ),
        "random_seed": args.seed,
        "progressive_trace": [
            {
                "distance": distance,
                "before": before,
                "after": after,
            }
            for distance, before, after in trace
        ],
    }

    metadata_json.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    with metadata_json.open(
        "w",
        encoding="utf-8",
    ) as handle:
        json.dump(
            metadata,
            handle,
            indent=2,
            ensure_ascii=False,
        )

    print("\n========== Final result ==========")
    print(f"Selected codes = {len(selected_codebook)}")
    print(f"Iterations = {iterations}")
    print(
        "Observed minimum pairwise distance = "
        f"{observed_min_distance}"
    )
    print(f"Elapsed time = {elapsed_seconds:.2f} s")
    print(f"Codebook CSV = {output_csv}")
    print(f"Run metadata = {metadata_json}")


if __name__ == "__main__":
    main()
