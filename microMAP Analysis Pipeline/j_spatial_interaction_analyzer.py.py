def load_centroids_from_dir(centroid_dir: str) -> pd.DataFrame:
    """
    [I/O Operations] Dynamically locates and parses the absolute centroid CSV files.

    """
    if not os.path.isdir(centroid_dir):
        raise FileNotFoundError(f"Directory missing: {centroid_dir}")

    csv_files = [f for f in os.listdir(centroid_dir) if f.endswith("_centroids.csv")]
    if not csv_files:
        raise FileNotFoundError(f"No *_centroids.csv identified in {centroid_dir}. Please ensure upstream centroid analysis is complete.")

    if len(csv_files) > 1:
        print("[Warning] Multiple *_centroids.csv detected. Defaulting to:", csv_files[0])

    csv_path = os.path.join(centroid_dir, csv_files[0])
    print(f"[Load] Utilizing centroid matrix: {csv_path}")
    df = pd.read_csv(csv_path)
    return df

class SpatialInteractionAnalyzer:
    """
    Multi-Scale Spatial Ecology Analyzer Suite:
    - Microscale (Cell-to-Cell): Evaluates heterotypic interactions against null permutations (Enrichment & P-values).
    - Self-Aggregation: Analyzes homotypic spatial clustering via DBSCAN.
    - Mesoscale: Maps spatial niches through multi-radius sliding windows and topological clustering.
    - Network Graphs: Generates cross-species interaction networks based on spatial significance.
    """

    def __init__(self, pixel_to_um: float):
        self.pixel_to_um = float(pixel_to_um)

    # ------------- Utility Functions-------------
    def um_to_pixels(self, um: float) -> float:
        return um / self.pixel_to_um

    def pixels_to_um(self, pixels: float) -> float:
        return pixels * self.pixel_to_um

    def infer_original_shape(self, df, output_dir):
        """
        [Memory Optimization] Extracts macro-array dimensions exclusively via TIFF metadata headers,
        circumventing whole-slide memory loading to categorically prevent OOM failures.
        
        """
        import os

        # Potential reference images generated by upstream pipelines
        cand_names = [
            "labels_centroids.tif",
            "labels_centroid.tif",
            "labels.tif",
        ]

        search_dirs = [
            output_dir,
            os.path.dirname(output_dir),
            os.path.dirname(os.path.dirname(output_dir)),
        ]

        for d in search_dirs:
            if not d:
                continue
            for name in cand_names:
                path = os.path.join(d, name)
                if os.path.isfile(path):
                    try:
                        # Fetch ONLY header metadata. Memory overhead ≈ 0 MB.
                        import tifffile as tiff
                        with tiff.TiffFile(path) as tif:
                            c_shape = tif.series[0].shape
                        
                        # Evaluate structural dimensions (C, H, W vs H, W)
                        if len(c_shape) > 2:
                            H, W = c_shape[:2]
                        else:
                            H, W = c_shape
                            
                        print(f"[Mesoscale] Master dimensions acquired via TIFF header ({path}): W={W}, H={H}")
                        return (H, W)
                    except Exception as e:
                        print(f"[Mesoscale] Metadata extraction failed for {path}: {e}")

        # Absolute Fallback: Estimate bounding box using global spatial coordinates
        H = int(df['centroid_row'].max()) + 20
        W = int(df['centroid_col'].max()) + 20
        print(f"[Mesoscale] No valid reference TIFF located. Estimating frame size via coordinate boundaries: W={W}, H={H}")
        return (H, W)

